"""Regenerates Sources/Core/Showcase/ShowcaseLibraryContent.swift from the approved Foundation Track articles.
Usage: showcase_library_fixture.py <dir with the dNN-*.md articles> (public practice content, no member data)."""
import pathlib, re, sys
H = pathlib.Path(sys.argv[1]).parent
PILLAR = {2: "nutrition", 8: "nutrition", 3: "mouvement", 9: "mouvement", 12: "mouvement", 4: "sommeil", 10: "sommeil", 5: "stress", 11: "stress"}
SLUG_FIX = {"exercise-snacks-small-signals-that-add-up": "exercise-snacks-foundation"}
BODIES = {"light-sets-your-body-clock", "the-3-2-1-rule"}
rows = []; bodies = {}
for f in sorted(pathlib.Path(sys.argv[1]).glob("d[0-9][0-9]-*.md")):
    t = f.read_text()
    fm, body = re.match(r"^---\n(.*?)\n---\n(.*)$", t, re.S).groups()
    meta = {}
    for line in fm.splitlines():
        k, _, v = line.partition(":"); v = v.strip()
        if len(v) > 1 and v[0] == v[-1] and v[0] in "\"'": v = v[1:-1]
        meta[k.strip()] = v
    body = body.strip()
    first, _, rest = body.partition("\n\n")
    if first.strip().strip("*_ ").rstrip(".") == meta["summary"].strip().rstrip("."):
        body = rest.strip()
    day = int(meta["day"]); slug = SLUG_FIX.get(meta["slug"], meta["slug"])
    mins = int(re.search(r"\d+", meta.get("reading_time", "3")).group())
    rows.append((day, slug, meta["title"], meta["summary"], mins, PILLAR.get(day, "")))
    if slug in BODIES: bodies[slug] = body
rows.sort(key=lambda r: (r[0], r[2]))
def sw(s): return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'
out = ["#if DEBUG", "import Foundation", "",
       "/// The 29 Foundation Track reads as the library lists them (title, summary, day, reading time, pillar: the rows published on",
       "/// CM OS on 2026-11-08, public practice content, not member data) and the text of two of them for the reader shot.",
       "/// Generated by `Scripts/showcase_library_fixture.py`; do not edit by hand.",
       "enum ShowcaseLibraryContent {",
       "    /// (day, slug, title, summary, minutes, pillar)", "    static let articles: [(day: Int, slug: String, title: String, summary: String, minutes: Int, pillar: String)] = ["]
for r in rows:
    out.append(f"        ({r[0]}, {sw(r[1])}, {sw(r[2])}, {sw(r[3])}, {r[4]}, {sw(r[5])}),")
out.append("    ]"); out.append("")
out.append("    static func body(slug: String) -> String? {\n        switch slug {")
for slug, b in bodies.items():
    assert '"""' not in b and '\\' not in b
    out.append(f'        case {sw(slug)}: return """\n{b}\n"""')
out.append("        default: return nil\n        }\n    }\n}\n#endif")
(pathlib.Path(__file__).resolve().parent.parent / "Sources/Core/Showcase/ShowcaseLibraryContent.swift").write_text("\n".join(out) + "\n")
print(len(rows))
