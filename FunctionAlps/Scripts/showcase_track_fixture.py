#!/usr/bin/env python3
"""Regenerate the Foundation Track fixture of the showcase screenshots (Debug only).

The showcase (Sources/Core/Showcase) answers the track calls from REAL CM OS content so the
screenshots show exactly what a member reads. This script turns one export into
Sources/Core/Showcase/ShowcaseTrackContent.swift.

Export (run on CM OS, save the single JSON value to a file):

    select json_build_object(
      'exported_at', now(),
      'days', (select json_agg(t order by day) from (select day,title_en,title_fr,focus_en,focus_fr,video_url_en,
         video_url_fr,read_slug,questionnaire_id,actions,push,card_en,card_fr,image_url,image_alt_en,image_alt_fr
         from public.track_day where track_code='foundation_v1') t),
      'questionnaires', (select json_agg(t order by day) from (select id,day,version,title_en,title_fr,intro_en,
         intro_fr,done_en,done_fr,est_minutes,counts_toward_review from public.track_questionnaire
         where track_code='foundation_v1' and active) t),
      'questions', (select json_agg(t order by questionnaire_id, screen, position) from (select q.id,
         q.questionnaire_id,q.question_key,q.screen,q.position,q.kind,q.prompt_en,q.prompt_fr,q.help_en,q.help_fr,
         q.options,q.max_select,q.min_value,q.max_value,q.step,q.unit,q.required,q.voice,q.show_if,q.prefill,
         q.variants from public.track_question q join public.track_questionnaire tq on tq.id=q.questionnaire_id
         where tq.track_code='foundation_v1' and tq.active) t),
      'cards', (select json_agg(t) from (select <ActionCardRow.columns> from public.habit_bank h where h.id::text in
         (select distinct a->>'habit_bank_id' from public.track_day d, jsonb_array_elements(d.actions) a
          where d.track_code='foundation_v1')) t),
      'reads', (select json_agg(json_build_object('slug', slug, 'title', title, 'body_md', body_md))
         from public.kb_nodes where slug in (select read_slug from public.track_day where track_code='foundation_v1')
         and published_at is not null)
    ) as export;

Usage: python3 Scripts/showcase_track_fixture.py export.json
"""
import json
import pathlib
import sys

OUT = pathlib.Path(__file__).resolve().parent.parent / "Sources/Core/Showcase/ShowcaseTrackContent.swift"


def literal(value) -> str:
    text = json.dumps(value, ensure_ascii=False, separators=(",", ":"))
    assert '"""##' not in text
    return '##"""\n' + text + '\n"""##'


def main(path: str) -> None:
    export = json.load(open(path))
    parts = ["days", "questionnaires", "questions", "cards", "reads"]
    lines = [
        "#if DEBUG",
        "// GENERATED by Scripts/showcase_track_fixture.py from a CM OS export — do not edit by hand.",
        f"// Exported {export.get('exported_at', '?')}: the Foundation Track (foundation_v1) as members read it.",
        "// Practice content only (no member data): days, questionnaires, questions, action cards, the day's reads.",
        "enum ShowcaseTrackContent {",
    ]
    for key in parts:
        lines.append(f"    static let {key} = {literal(export[key])}")
    lines += ["}", "#endif", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes): " + ", ".join(f"{k} {len(export[k])}" for k in parts))
    write_shots(export)


SHOTS = pathlib.Path(__file__).resolve().parent / "track_shots.tsv"
HOME_PAGES = 5  # pages of Home per day (identical bottom pages are dropped after the shoot)


def write_shots(export) -> None:
    """The Foundation Track shot list, in the order a member meets the screens: per day, Home page by page, then that
    day's questionnaire (intro, each screen, done), the day's read, the card of each action new that day, and from
    day 8 the approved day-7 summary. Day 15 = the two weeks are over. One line: name<TAB>showcase arguments."""
    screens = {}
    for q in export["questions"]:
        screens.setdefault(q["questionnaire_id"], set()).add(q["screen"])
    by_day = {q["day"]: q["id"] for q in export["questionnaires"]}
    cards = {c["id"] for c in export["cards"]}
    seen_cards = set()
    rows = []
    for d in range(1, 16):
        day = next((x for x in export["days"] if x["day"] == min(d, 14)), None)
        base = f"-FAShowcase track -FATrackDay {d}"
        for page in range(HOME_PAGES):
            rows.append((f"t-d{d:02d}-a-home-p{page}", f"{base} -FAPage {page}"))
        if d == 8:
            rows.append((f"t-d{d:02d}-b-summary", f"-FAShowcase track-summary -FATrackDay {d}"))
        qid = by_day.get(d) if d <= 14 else None
        if qid:
            qbase = f"-FAShowcase track-q -FATrackDay {d} -FAQuestionnaire {qid}"
            rows.append((f"t-d{d:02d}-c-q0-intro", f"{qbase} -FAQStep intro"))
            for i, screen in enumerate(sorted(screens.get(qid, []))):
                rows.append((f"t-d{d:02d}-c-q{i + 1}-screen{screen}", f"{qbase} -FAQStep {screen}"))
            rows.append((f"t-d{d:02d}-c-q9-done", f"{qbase} -FAQStep done"))
        if d <= 14 and day and day.get("read_slug"):
            rows.append((f"t-d{d:02d}-d-read", f"-FAShowcase track-read -FATrackDay {d} -FASlug {day['read_slug']}"))
        if d <= 14 and day:
            for a in day["actions"]:
                cid = a.get("habit_bank_id")
                if a.get("new") and cid in cards and cid not in seen_cards:
                    seen_cards.add(cid)
                    rows.append((f"t-d{d:02d}-e-card-{a['key']}",
                                 f"-FAShowcase track-card -FATrackDay {d} -FACard {cid} -FAFace {a.get('face') or 'standard'}"))
    SHOTS.write_text("".join(f"{n}\t{a}\n" for n, a in rows))
    print(f"wrote {SHOTS}: {len(rows)} shots")


if __name__ == "__main__":
    main(sys.argv[1])
