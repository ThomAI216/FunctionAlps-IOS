"""Generate the SQL that publishes docs/legal/texts/*.md as new consent_definitions versions.

Usage: python3 docs/legal/tools/build_migration.py > docs/legal/pending/<name>.sql
Each document becomes version N+1 (en + fr), copying every other column from the current
approved row; the old rows are superseded. Bodies are embedded verbatim with dollar quoting and
checked to contain no em dash. Nothing here runs by itself: the output is applied by hand, after review."""
import os, sys
ROOT = os.path.join(os.path.dirname(__file__), '..', 'texts')
# key -> (current version, summaries {locale: new summary or None to keep})
DOCS = {
  'terms_of_use': ('v9', {'en': 'The rules for using FunctionAlps, and what it is not.',
                          'fr': 'Les règles d’utilisation de FunctionAlps, et ce qu’elle n’est pas.'}),
  'privacy_policy': ('v13', {}),
  'ai_analysis': ('v8', {}),
  'health_data_processing': ('v7', {'en': 'Explicit consent to process your health data, including the AI analysis that produces your scores and reports.',
                                    'fr': 'Consentement explicite au traitement de vos données de santé, y compris l’analyse par IA qui produit vos scores et vos rapports.'}),
  'medical_documents_sharing': ('v2', {}),
  'usage_analytics': ('v3', {}),
  'marketing_comms': ('v3', {}),
}
def q(s, tag='fa_body'):
    assert f'${tag}$' not in s
    return f'${tag}${s}${tag}$'
def main(note):
    out = ['-- GENERATED by docs/legal/tools/build_migration.py. Do not edit by hand: edit docs/legal/texts and regenerate.',
           'begin;', 'do $mig$', 'declare n int;', 'begin']
    for key, (cur, summaries) in DOCS.items():
        nxt = 'v' + str(int(cur[1:]) + 1)
        out.append(f"  if exists (select 1 from public.consent_definitions where consent_key = '{key}' and version = '{nxt}') then raise exception '{key} {nxt} already exists'; end if;")
        out.append(f"  if (select count(*) from public.consent_definitions where consent_key = '{key}' and version = '{cur}' and superseded_at is null and review_status = 'approved') <> 2 then raise exception '{key} {cur} is not the current approved en+fr pair'; end if;")
        for loc in ('en', 'fr'):
            body = open(os.path.join(ROOT, f'{key}.{loc}.md')).read()
            assert '—' not in body and '–' not in body, (key, loc)
            summ = summaries.get(loc)
            out.append(f"""  insert into public.consent_definitions (consent_key, version, locale, title, summary, body_md, required, display_order, legal_basis, doc_kind, basis, review_status, approved_by, approved_at, effective_from, approval_note)
  select consent_key, '{nxt}', locale, title, {q(summ, 'fa_sum') if summ else 'summary'}, {q(body)},
         required, display_order, legal_basis, doc_kind, basis, 'approved', 'Thomas Convent, operator, FunctionAlps', now(), now(), {q(nxt + ' = ' + cur + '. ' + note, 'fa_note')}
    from public.consent_definitions where consent_key = '{key}' and version = '{cur}' and locale = '{loc}' and superseded_at is null and review_status = 'approved';
  get diagnostics n = row_count;
  if n <> 1 then raise exception '{key} {nxt} {loc}: expected 1 row, got %', n; end if;""")
        out.append(f"  update public.consent_definitions set superseded_at = now() where consent_key = '{key}' and version = '{cur}' and superseded_at is null;")
    out += ['end $mig$;', '-- Inspect, then: commit;  (or rollback;)', '']
    return '\n'.join(out)
if __name__ == '__main__':
    print(main(sys.argv[1] if len(sys.argv) > 1 else 'Revision of 2026-11 (see docs/legal/README.md).'))
